function getLanguage() {
    const saved = localStorage.getItem("royalGarageLanguage");
    return translations[saved] ? saved : "uk";
}

function t(key, fallback = "") {
    const lang = getLanguage();
    return translations[lang]?.[key] ?? translations.uk?.[key] ?? fallback;
}

function setLanguage(lang) {
    if (!translations[lang]) lang = "uk";

    localStorage.setItem("royalGarageLanguage", lang);
    document.documentElement.lang = lang;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const value = translations[lang][element.dataset.i18n];
        if (value !== undefined) element.textContent = value;
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const value = translations[lang][element.dataset.i18nPlaceholder];
        if (value !== undefined) element.placeholder = value;
    });

    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
        const value = translations[lang][element.dataset.i18nTitle];
        if (value !== undefined) element.title = value;
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((element) => {
        const value = translations[lang][element.dataset.i18nAriaLabel];
        if (value !== undefined) element.setAttribute("aria-label", value);
    });

    document.querySelectorAll("[data-i18n-alt]").forEach((element) => {
        const value = translations[lang][element.dataset.i18nAlt];
        if (value !== undefined) element.alt = value;
    });

    document.querySelectorAll("[data-i18n-label]").forEach((element) => {
        const value = translations[lang][element.dataset.i18nLabel];
        if (value === undefined) return;
        const textNode = Array.from(element.childNodes).find(
            (node) => node.nodeType === Node.TEXT_NODE && node.textContent.trim()
        );
        if (!textNode) return;
        const leading = textNode.textContent.match(/^\s*/)?.[0] || "";
        const trailing = textNode.textContent.match(/\s*$/)?.[0] || "";
        textNode.textContent = `${leading}${value}${trailing}`;
    });

    document.querySelectorAll("[data-i18n-nodes]").forEach((element) => {
        const mappings = element.dataset.i18nNodes.split("|").filter(Boolean);
        const textNodes = Array.from(element.childNodes).filter(
            (node) => node.nodeType === Node.TEXT_NODE && node.textContent.trim()
        );
        mappings.forEach((mapping) => {
            const separator = mapping.indexOf(":");
            if (separator === -1) return;
            const index = Number(mapping.slice(0, separator));
            const key = mapping.slice(separator + 1);
            const textNode = textNodes[index];
            const value = translations[lang][key];
            if (!textNode || value === undefined) return;
            const leading = textNode.textContent.match(/^\s*/)?.[0] || "";
            const trailing = textNode.textContent.match(/\s*$/)?.[0] || "";
            textNode.textContent = `${leading}${value}${trailing}`;
        });
    });

    document.querySelectorAll("[data-lang]").forEach((button) => {
        button.classList.toggle("active", button.dataset.lang === lang);
    });

    document.dispatchEvent(new CustomEvent("royalGarageLanguageChange", { detail: { lang } }));
}

