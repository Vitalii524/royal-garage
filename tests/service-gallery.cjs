const assert=require('node:assert/strict'),vm=require('node:vm'),fs=require('node:fs');
const {parseHTML}=require('linkedom');
const {window,document}=parseHTML('<html><body></body></html>');
vm.runInNewContext(fs.readFileSync('public/js/service-gallery.js','utf8'),{window,document,URL,setTimeout,clearTimeout});
const G=window.RGServiceGallery,photos=['data:image/jpeg;base64,eA==','data:image/png;base64,eQ=='];
const g=G.gallery(photos,'Колаж');document.body.append(g);
assert.equal(g.querySelector('.rg-service-counter').textContent,'1 / 2');
g.querySelector('.rg-service-next').click();assert.equal(g.querySelector('img').src,photos[1]);
assert.equal(g.querySelector('.rg-service-counter').textContent,'2 / 2');
g.querySelector('.rg-service-next').click();assert.equal(g.querySelector('.rg-service-counter').textContent,'1 / 2');
g.querySelectorAll('.rg-service-dots button')[1].click();assert.equal(g.querySelector('img').src,photos[1]);
const stage=g.querySelector('.rg-service-stage');
const start=new window.Event('touchstart');start.touches=[{clientX:200,clientY:30}];stage.dispatchEvent(start);
const end=new window.Event('touchend');end.changedTouches=[{clientX:100,clientY:35}];stage.dispatchEvent(end);
assert.equal(g.querySelector('.rg-service-counter').textContent,'1 / 2');
assert.equal(G.media('/api/media/videos/abc','video').tagName,'VIDEO');
const full=G.media('/api/service-catalog/images/abc','x',true),thumb=G.media('/api/service-catalog/images/abc','x');
assert.equal(full.src,'/api/service-catalog/images/abc');assert.match(thumb.src,/preview=1/);
const card=G.card({name:'Test',photos,description:'Long description',priceUah:null},'Category');
assert.equal(card.querySelector('strong').textContent,'Ціна договірна');assert.equal(card.querySelectorAll('h3').length,1);
assert.equal(photos.length,2);assert.deepEqual(photos,['data:image/jpeg;base64,eA==','data:image/png;base64,eQ==']);
console.log('PASS: arrows, dots, swipe, wraparound, media type, original/thumbnail URLs, compact cards, original array intact');
